// Local fixture only: node tests/browser/fixture/server.mjs, then playwright-cli
// --raw run-code --filename=tests/browser/personal-records.js. Never uses real Auth.
async (page) => {
  const base = 'http://127.0.0.1:5182'
  const checks = []
  const errors = []
  const external = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('request', (request) => { if (!request.url().startsWith(base + '/') && !request.url().startsWith('data:')) external.push(request.url()) })
  const assert = (condition, name) => { if (!condition) throw new Error(name); checks.push(name) }
  const posts = () => page.locator('#my-posts .account-post')
  const ratings = () => page.locator('#my-ratings .account-rating')
  const visible = (text) => page.locator('main').getByText(text, { exact: true }).waitFor()
  async function count(selector, expected) { await page.waitForFunction(({ selector, expected }) => document.querySelectorAll(selector).length === expected, { selector, expected }) }
  async function fresh(path) { await page.goto(base + path) }
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await fresh('/account')
  await visible('fixture-a@zju.edu.cn')
  assert(await page.locator('.account-record-entry').count() === 2 && await page.locator('.account-post,.account-rating').count() === 0, 'personal center contains two subpage entries and no expanded records')
  for (const kind of ['posts', 'ratings']) {
    const selector = kind === 'posts' ? '#my-posts .account-post' : '#my-ratings .account-rating'
    await fresh(`/account/${kind}`)
    await count(selector, 6)
    await page.getByRole('navigation', { name: '结果分页', exact: true }).getByText('第 1 / 3 页 · 共 14 条', { exact: true }).waitFor()
    assert(await page.getByRole('button', { name: '上一页', exact: true }).isDisabled(), `${kind}: first page shows six records and disables previous`)
    await page.getByRole('button', { name: '下一页', exact: true }).focus()
    await page.keyboard.press('Enter')
    await page.waitForURL((url) => url.searchParams.get('page') === '2')
    await page.waitForFunction((kind) => document.activeElement?.id === `my-${kind === 'posts' ? 'posts' : 'ratings'}-title`, kind)
    assert(await page.locator(selector).count() === 6, `${kind}: keyboard paging updates URL, focuses heading and shows six distinct next records`)
    const link = page.locator(selector).first().getByRole('link', { name: kind === 'posts' ? '查看发布' : /查看美食详情/ })
    const href = await link.getAttribute('href')
    assert(await page.evaluate((href) => new URL(href, location.href).searchParams.get('returnTo'), href) === `/account/${kind}?page=2`, `${kind}: detail link preserves exact personal list page`)
    await link.click()
    await page.locator('.food-detail-card').waitFor()
    await page.getByRole('link', { name: kind === 'posts' ? '返回我的发布' : '返回我的评分', exact: true }).click()
    await page.waitForURL((url) => url.pathname === `/account/${kind}` && url.searchParams.get('page') === '2')
    await count(selector, 6)
    assert(true, `${kind}: detail breadcrumb returns to page two`)
    await page.getByRole('button', { name: '下一页', exact: true }).click()
    await count(selector, 2)
    assert(await page.getByRole('button', { name: '下一页', exact: true }).isDisabled(), `${kind}: last page contains remaining two records`)
    await page.goBack()
    await page.waitForURL((url) => url.searchParams.get('page') === '2')
    await count(selector, 6)
    assert(true, `${kind}: browser Back restores prior page`)
    await page.reload()
    await count(selector, 6)
    assert(page.url().endsWith('?page=2'), `${kind}: deep-link refresh preserves page two`)
    if (kind === 'posts') {
      await page.locator('.account-section-heading').getByRole('link', { name: '发布一道菜', exact: true }).click()
      await page.waitForURL((url) => url.pathname === '/food/new')
      assert(await page.evaluate(() => new URL(location.href).searchParams.get('returnTo')) === '/account/posts?page=2', 'posts: publish entry carries only the original personal page two return')
      await page.locator('.breadcrumb').getByText('返回我的发布', { exact: true }).click()
      await page.waitForURL((url) => url.pathname === '/account/posts' && url.searchParams.get('page') === '2')
      await count(selector, 6)
      assert(true, 'posts: leaving publish page returns to personal page two')
    }
    await fresh(`/account/${kind}?page=999`)
    await count(selector, 2)
    await page.waitForURL((url) => url.searchParams.get('page') === '3')
    assert(true, `${kind}: out-of-range page clamps only after result count arrives`)
    await fresh(`/account/${kind}?page=1.5`)
    await count(selector, 6)
    await page.waitForURL((url) => !url.searchParams.has('page'))
    assert(true, `${kind}: invalid page resets safely to first page`)
    await page.getByLabel('查询响应', { exact: true }).selectOption('failure')
    await page.getByRole('button', { name: kind === 'posts' ? '重试我的发布' : '重试我的评分', exact: true }).waitFor()
    assert(await page.locator(selector).count() === 0, `${kind}: failed request clears prior content and offers retry`)
    await page.getByRole('button', { name: '恢复响应以重试', exact: true }).click()
    await page.getByRole('button', { name: kind === 'posts' ? '重试我的发布' : '重试我的评分', exact: true }).click()
    await count(selector, 6)
    assert(true, `${kind}: retry reloads current user's records`)
    await page.getByLabel('查询响应', { exact: true }).selectOption('empty')
    await visible(kind === 'posts' ? '还没有发布美食' : '还没有评分记录')
    assert(await page.getByRole('navigation', { name: '结果分页', exact: true }).count() === 0, `${kind}: honest empty state has no pagination`)
    if (kind === 'posts') {
      await page.locator('.account-empty').getByRole('link', { name: '发布一道菜', exact: true }).click()
      await page.waitForURL((url) => url.pathname === '/food/new')
      assert(await page.evaluate(() => new URL(location.href).searchParams.get('returnTo')) === '/account/posts', 'posts: empty-state publish entry retains a canonical personal return')
      await page.locator('.breadcrumb').getByText('返回我的发布', { exact: true }).click()
      await visible('还没有发布美食')
      assert(true, 'posts: empty-state publish page returns to the original personal list')
    }
  }
  await fresh('/account/ratings')
  await count('#my-ratings .account-rating', 6)
  await ratings().first().locator('.account-rating-image').scrollIntoViewIfNeeded()
  await page.waitForFunction(() => { const image = document.querySelector('.account-rating img'); return image?.complete && image.naturalWidth > 0 })
  assert(await ratings().first().locator('img').count() === 1, 'ratings use the actual visible food thumbnail')
  await ratings().nth(1).getByText('暂无图片', { exact: true }).waitFor()
  assert(true, 'missing rating food image uses honest placeholder')
  const removed = ratings().nth(2)
  assert((await removed.innerText()).includes('原菜品已撤下或不再可见') && await removed.locator('img,a,.food-image').count() === 0, 'withdrawn rating keeps score/date without restricted name, image or link')
  await ratings().nth(3).locator('.account-rating-image').scrollIntoViewIfNeeded()
  await ratings().nth(3).getByText('图片暂时无法加载', { exact: true }).waitFor()
  assert(true, 'failed rating image uses recoverable honest placeholder')
  for (const width of [320, 375, 390]) {
    await page.setViewportSize({ width, height: 844 })
    for (const kind of ['posts', 'ratings']) {
      await fresh(`/account/${kind}?page=2`)
      await count(kind === 'posts' ? '#my-posts .account-post' : '#my-ratings .account-rating', 6)
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), `${kind}: no horizontal overflow at ${width}px`)
      await page.getByRole('button', { name: '下一页', exact: true }).click()
      await page.waitForURL((url) => url.searchParams.get('page') === '3')
      assert(await page.getByRole('button', { name: '下一页', exact: true }).isDisabled(), `${kind}: mobile pagination remains usable at ${width}px`)
      if (width === 390) await page.screenshot({ path: `scratch/personal-records/${kind}-390.png`, fullPage: true, animations: 'disabled' })
    }
  }
  for (const kind of ['posts', 'ratings']) {
    const selector = kind === 'posts' ? '#my-posts .account-post' : '#my-ratings .account-rating'
    await fresh(`/account/${kind}?page=2`)
    await count(selector, 6)
    await page.getByLabel('响应延迟', { exact: true }).selectOption('2500')
    await page.getByLabel('查询响应', { exact: true }).selectOption('empty')
    await page.getByLabel('测试身份', { exact: true }).selectOption('b')
    await page.getByLabel('查询响应', { exact: true }).selectOption('normal')
    await page.getByLabel('响应延迟', { exact: true }).selectOption('100')
    await page.locator('main').getByText('B的本地测试菜品', { exact: true }).waitFor()
    await page.waitForURL((url) => !url.searchParams.has('page'))
    // Let the intentionally delayed old-account read settle before inspecting again.
    await page.waitForTimeout(2700)
    assert(await page.locator(selector).count() === 1 && !(await page.locator('main').innerText()).includes('A的'), `${kind}: switching account drops stale A response and clamps page for B only`)
    await page.getByRole('button', { name: '退出登录', exact: true }).click()
    await visible(kind === 'posts' ? '登录后查看我的发布' : '登录后查看我的评分')
    assert(await page.locator(selector).count() === 0 && !(await page.locator('main').innerText()).includes('B的本地测试菜品'), `${kind}: logout removes all personal records`)
  }
  await fresh('/account/ratings?page=2')
  await count('#my-ratings .account-rating', 6)
  await page.getByLabel('测试身份', { exact: true }).selectOption('guest')
  await visible('登录后查看我的评分')
  await page.locator('.account-empty').getByRole('link', { name: /使用浙大邮箱登录/ }).click()
  assert(await page.evaluate(() => new URL(location.href).searchParams.get('returnTo')) === '/account/ratings?page=2', 'guest login link keeps original personal subpage and page two')
  await page.getByLabel('浙大邮箱', { exact: true }).fill('fixture-a@zju.edu.cn')
  await page.getByRole('button', { name: '发送验证码', exact: true }).click()
  await page.getByLabel('邮件验证码', { exact: true }).fill('123456')
  await page.getByRole('button', { name: '验证并登录', exact: true }).click()
  await page.waitForURL((url) => url.pathname === '/account/ratings' && url.searchParams.get('page') === '2')
  await count('#my-ratings .account-rating', 6)
  assert(true, 'isolated login resumes original personal ratings subpage and page two')
  assert(errors.length === 0, 'no uncaught browser errors: ' + errors.join('; '))
  assert(external.length === 0, 'isolated checks issued no external service requests: ' + external.join('; '))
  return { fixtureOnly: true, checks, count: checks.length, screenshots: ['scratch/personal-records/posts-390.png', 'scratch/personal-records/ratings-390.png'] }
}
