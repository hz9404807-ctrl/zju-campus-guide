// Isolated browser regression. Start `node tests/browser/fixture/server.mjs` first.
// `playwright-cli -s=brand-account --raw run-code --filename=tests/browser/brand-account.js`
// Real components + memory service fixture. This never proves live Supabase/Auth/RLS.
async (page) => {
  const base = 'http://127.0.0.1:5182'
  const checks = []
  const failures = []
  const screenshots = []
  const mobileAccountBounds = []
  const pageErrors = []
  const consoleErrors = []
  const expectedImageErrors = []
  const external = []
  page.on('pageerror', (error) => pageErrors.push(error.message))
  page.on('console', (message) => { if (message.type() === 'error') { const entry = { text: message.text(), url: message.location().url }; if (entry.url.startsWith(base + '/__fixture/not-found.jpg') && /404/.test(entry.text)) expectedImageErrors.push(entry); else consoleErrors.push(entry) } })
  page.on('request', (request) => { if (!request.url().startsWith(base + '/') && !request.url().startsWith('data:')) external.push(request.url()) })
  const check = (condition, label) => (condition ? checks : failures).push(label)
  const visible = (text) => page.locator('main').getByText(text, { exact: true }).waitFor({ state: 'visible' })
  const mainText = () => page.locator('main').innerText()
  const details = () => page.locator('.account-details-card')
  async function saveScreenshot(name, locator) {
    const file = `scratch/brand-ui/${name}.png`
    if (locator) await locator.screenshot({ path: file, animations: 'disabled' })
    else { await page.locator('main').focus(); await page.keyboard.press('Control+Home'); await page.screenshot({ path: file, fullPage: true, animations: 'disabled' }) }
    screenshots.push(file)
  }
  async function fresh(path = '/account') { await page.goto(base + path); if (path.split('?')[0] === '/account') { await visible('fixture-a@zju.edu.cn'); await visible('A 的本地测试签名') } }
  async function noOverflow(label) { check(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), label) }
  try {
    await page.setViewportSize({ width: 1440, height: 1000 })
    await page.emulateMedia({ reducedMotion: 'reduce' })
    await fresh()
    check(!((await mainText()).includes('fixture-b@zju.edu.cn')), 'account A sees its own email and no B identity')
    check(await page.locator('.account-post,.account-rating').count() === 0, 'personal center contains entry cards instead of loading all records')
    await saveScreenshot('account-desktop')
    await saveScreenshot('profile-display-desktop', details())
    await page.locator('.account-record-links').getByRole('link', { name: /我的发布/ }).click()
    const posts = page.locator('#my-posts .account-post')
    await posts.first().waitFor()
    check(await posts.count() === 6, 'owned posts show at most six records on the first page')
    for (const post of await posts.all()) await post.locator('.account-post-image').scrollIntoViewIfNeeded()
    await posts.nth(3).getByText('图片暂时无法加载', { exact: true }).waitFor()
    check(await posts.nth(1).getByText('暂无图片', { exact: true }).isVisible(), 'missing food image uses an honest placeholder')
    check(await posts.nth(0).locator('img').evaluate((img) => img.complete && img.naturalWidth > 0), 'actual test image is loaded in owned post')
    check(await posts.nth(2).getByText('已撤下', { exact: true }).isVisible(), 'withdrawn owner post remains manageable with thumbnail')
    const contentBox = await posts.nth(0).locator('.account-post-content').boundingBox()
    const imageBox = await posts.nth(0).locator('.account-post-image').boundingBox()
    check(imageBox && contentBox && imageBox.x >= contentBox.x + contentBox.width - 1, 'desktop owned thumbnail is to the right of content')
    await saveScreenshot('posts-desktop', page.locator('#my-posts'))
    await posts.nth(0).getByRole('button', { name: '撤下', exact: true }).click()
    await posts.nth(0).getByRole('button', { name: '取消', exact: true }).click()
    check(await posts.nth(0).getByText('已发布', { exact: true }).isVisible(), 'withdraw confirmation cancellation preserves the post')
    await posts.nth(0).getByRole('button', { name: '撤下', exact: true }).click()
    await posts.nth(0).getByRole('button', { name: '确认撤下', exact: true }).click()
    await posts.nth(0).getByRole('button', { name: '恢复发布', exact: true }).waitFor()
    check(await posts.nth(0).getByRole('link', { name: '查看发布', exact: true }).count() === 0, 'withdrawn item stops offering the public detail link')
    await posts.nth(0).getByRole('button', { name: '恢复发布', exact: true }).click()
    await posts.nth(0).getByText('已发布', { exact: true }).waitFor()
    check(true, 'owned thumbnail layout preserves existing withdraw and restore actions')
    await page.locator('.breadcrumb').getByText('返回个人中心', { exact: true }).click()
    await visible('A 的本地测试签名')
    await details().getByRole('button', { name: '编辑资料', exact: true }).click()
    await page.getByLabel('个性签名', { exact: true }).fill('A的未保存草稿')
    await details().getByRole('button', { name: '取消', exact: true }).click()
    await visible('A 的本地测试签名')
    check(!(await mainText()).includes('A的未保存草稿'), 'cancel preserves the saved profile and discards draft')
    await details().getByRole('button', { name: '编辑资料', exact: true }).click()
    await page.getByRole('combobox', { name: '性别', exact: true }).selectOption('female')
    await page.getByRole('combobox', { name: '常驻校区', exact: true }).selectOption('玉泉')
    await page.getByLabel('个性签名', { exact: true }).fill('🍀'.repeat(121))
    check(await details().getByRole('button', { name: '保存资料', exact: true }).isDisabled(), '121 Unicode characters cannot be submitted')
    await page.getByLabel('个性签名', { exact: true }).fill('A本地保存后的签名')
    await saveScreenshot('profile-edit-desktop', details())
    await details().getByRole('button', { name: '保存资料', exact: true }).click()
    await visible('个人资料已保存')
    check((await details().innerText()).includes('玉泉校区') && (await details().innerText()).includes('A本地保存后的签名'), 'profile save displays selected campus and signature')
    await details().getByRole('button', { name: '编辑资料', exact: true }).click()
    await page.getByLabel('个性签名', { exact: true }).fill('失败后应保留的草稿')
    await page.getByLabel('模拟写入失败', { exact: true }).check()
    await details().getByRole('button', { name: '保存资料', exact: true }).click()
    await details().getByRole('alert').filter({ hasText: '模拟保存失败' }).waitFor()
    check(await page.getByLabel('个性签名', { exact: true }).inputValue() === '失败后应保留的草稿' && !(await details().innerText()).includes('个人资料已保存'), 'failed save keeps draft and never reports success')
    await page.getByLabel('模拟写入失败', { exact: true }).uncheck()
    await details().getByRole('button', { name: '保存资料', exact: true }).click()
    await visible('个人资料已保存')
    check(true, 'profile save can be retried after recovery')
    await page.getByLabel('查询响应', { exact: true }).selectOption('missing')
    await details().getByRole('alert').filter({ hasText: '个人资料尚待共享服务接入' }).waitFor()
    check(await details().getByRole('button', { name: '编辑资料', exact: true }).count() === 0, 'undeployed profile interface blocks editing and explains pending state')
    await page.getByRole('button', { name: '恢复响应以重试', exact: true }).click()
    await details().getByRole('button', { name: '重试个人资料', exact: true }).click()
    await visible('失败后应保留的草稿')
    check(true, 'missing-interface message retries into saved profile')
    await page.getByLabel('查询响应', { exact: true }).selectOption('failure')
    await details().getByRole('button', { name: '重试个人资料', exact: true }).waitFor()
    await page.getByRole('button', { name: '恢复响应以重试', exact: true }).click()
    await details().getByRole('button', { name: '重试个人资料', exact: true }).click()
    await visible('失败后应保留的草稿')
    check(true, 'personal details read failure exposes a working retry control')
    await page.getByLabel('查询响应', { exact: true }).selectOption('empty')
    await visible('失败后应保留的草稿')
    check(await page.locator('.account-record-entry').count() === 2, 'empty record mode keeps both separate record entrances')
    await page.getByLabel('查询响应', { exact: true }).selectOption('normal')
    await visible('失败后应保留的草稿')
    await details().getByRole('button', { name: '编辑资料', exact: true }).click()
    await page.getByLabel('个性签名', { exact: true }).fill('A正在保存时换B的私人草稿')
    await page.getByLabel('响应延迟', { exact: true }).selectOption('2500')
    await details().getByRole('button', { name: '保存资料', exact: true }).click()
    check(await details().getByRole('button', { name: '正在保存…', exact: true }).isDisabled() && await details().getByRole('button', { name: '取消', exact: true }).isDisabled(), 'pending save disables duplicate submission and cancellation')
    await page.getByLabel('测试身份', { exact: true }).selectOption('b')
    await visible('fixture-b@zju.edu.cn')
    await visible('还没有填写个性签名')
    check(!(await mainText()).includes('A正在保存时换B的私人草稿') && !(await mainText()).includes('个人资料已保存') && !(await mainText()).includes('A的本地测试菜品'), 'switching to B during delayed save clears A draft, posts, and late success')
    await page.getByLabel('响应延迟', { exact: true }).selectOption('100')
    await page.getByLabel('测试身份', { exact: true }).selectOption('a')
    await visible('fixture-a@zju.edu.cn'); await visible('失败后应保留的草稿')
    check(!(await mainText()).includes('A正在保存时换B的私人草稿'), 'cancelled cross-account save does not overwrite A saved details')
    await page.getByRole('button', { name: '退出登录', exact: true }).click()
    await visible('登录后查看你的内容')
    check(!(await mainText()).includes('fixture-a@zju.edu.cn') && !(await mainText()).includes('失败后应保留的草稿'), 'logout removes private email, profile and owned posts')
    await saveScreenshot('account-guest-desktop')
    await fresh('/food/aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa')
    await page.locator('.food-account-links').getByRole('link', { name: '个人中心', exact: true }).waitFor()
    await visible('你已经评分过该菜品')
    const actions = await page.locator('.food-account-links > *').all()
    const boxes = await Promise.all(actions.map((item) => item.boundingBox()))
    check(boxes.length === 3 && boxes.every((box) => box && Math.abs(box.y - boxes[0].y) < 1 && Math.abs(box.height - boxes[0].height) < 1), 'food account links and logout share identical desktop y and height')
    const accountLink = page.locator('.food-account-links').getByRole('link', { name: '个人中心', exact: true })
    await accountLink.focus(); await page.keyboard.press('Tab')
    check(await page.locator('.food-account-links').getByRole('link', { name: '我的发布', exact: true }).evaluate((node) => node === document.activeElement), 'keyboard Tab reaches next account action in order')
    await page.keyboard.press('Tab')
    check(await page.locator('.food-account-links').getByRole('button', { name: '退出登录', exact: true }).evaluate((node) => node === document.activeElement), 'keyboard Tab reaches logout button')
    await saveScreenshot('food-detail-desktop')
    await fresh('/guides')
    for (const keyword of ['保研', '奖学金', '竞赛']) {
      await page.getByRole('button', { name: keyword, exact: true }).click()
      await page.waitForFunction((expected) => document.getElementById('guide-search')?.value === expected, keyword)
      check(await page.getByLabel('你想办什么事？', { exact: true }).inputValue() === keyword, `academic quick search sets ${keyword}`)
    }
    await page.getByLabel('你想办什么事？', { exact: true }).dispatchEvent('compositionstart')
    await page.getByLabel('你想办什么事？', { exact: true }).fill('baoyan')
    check(page.url().includes('q=' + encodeURIComponent('竞赛')), 'simulated Chinese composition does not publish unfinished pinyin')
    await page.getByLabel('你想办什么事？', { exact: true }).fill('保研')
    await page.getByLabel('你想办什么事？', { exact: true }).dispatchEvent('compositionend')
    await page.waitForURL((url) => url.searchParams.get('q') === '保研')
    check(true, 'composition end publishes final Chinese query')
    await page.getByLabel('你想办什么事？', { exact: true }).fill('校园卡')
    await page.locator('.guide-card-title').first().waitFor()
    check((await mainText()).includes('校园卡'), 'public real guide dataset remains searchable')
    const guideLink = page.locator('.guide-card-title').first()
    await guideLink.click()
    await page.getByRole('heading', { name: '官方办事参考', exact: true }).waitFor()
    check(page.url().includes('/guides/'), 'public guide opens sourced detail without login')
    await saveScreenshot('guide-desktop')
    for (const width of [320, 375, 390]) {
      await page.setViewportSize({ width, height: 844 })
      await fresh()
      await noOverflow(`account has no horizontal overflow at ${width}px`)
      await details().getByRole('button', { name: '编辑资料', exact: true }).click()
      await page.getByLabel('个性签名', { exact: true }).fill('手机端本地测试签名')
      await noOverflow(`profile editor has no horizontal overflow at ${width}px`)
      await saveScreenshot(`account-edit-${width}`)
      await page.locator('.menu-toggle').click()
      await page.getByRole('navigation', { name: '手机主导航', exact: true }).waitFor()
      await noOverflow(`mobile menu has no horizontal overflow at ${width}px`)
      await page.keyboard.press('Escape')
      check(await page.locator('.menu-toggle').getAttribute('aria-expanded') === 'false', `Escape closes mobile menu at ${width}px`)
      await fresh('/food/aaaaaaaa-aaaa-4aaa-8aaa-aaaaaaaaaaaa')
      await page.locator('.food-account-links').getByRole('link', { name: '个人中心', exact: true }).waitFor()
      await visible('你已经评分过该菜品')
      await noOverflow(`food detail and account actions have no horizontal overflow at ${width}px`)
      const mobileBoxes = await Promise.all((await page.locator('.food-account-links > *').all()).map((action) => action.boundingBox()))
      mobileAccountBounds.push({ width, boxes: mobileBoxes })
      check(mobileBoxes.length === 3 && mobileBoxes.every((box) => box && Math.abs(box.y - mobileBoxes[0].y) < 1 && Math.abs(box.height - 44) < 1), `all three mobile account actions share one 44px row at ${width}px`)
      const barFile = `scratch/brand-ui/account-bar-${width}.png`
      await page.locator('.food-account-bar').screenshot({ path: barFile, animations: 'disabled', style: '.food-account-bar::before { content:"仅本机隔离测试 · 模拟登录"; display:block; margin-bottom:8px; color:#755523; font-size:11px; }' })
      screenshots.push(barFile)
      await saveScreenshot(`food-detail-${width}`)
    }
    await page.setViewportSize({ width: 1440, height: 1000 })
    await fresh('/')
    await page.locator('header img.brand-wordmark').waitFor()
    check(await page.locator('header img.brand-wordmark').evaluate((img) => img.complete && img.naturalWidth > 0), 'new supplied brand wordmark loads in shared header')
    await saveScreenshot('home-desktop')
    check(pageErrors.length === 0, 'no uncaught browser errors: ' + pageErrors.join('; '))
    check(consoleErrors.length === 0, 'no unexpected console errors: ' + consoleErrors.map((entry) => entry.text).join('; '))
    check(external.length === 0, 'fixture issued no external service or credential requests: ' + external.join('; '))
    if (failures.length) throw new Error('Failed assertions: ' + failures.join('; '))
    return { fixtureOnly: true, checks, failures, expectedImage404Count: expectedImageErrors.length, mobileAccountBounds, screenshots }
  } catch (error) {
    await saveScreenshot('failure')
    throw new Error('Passed checks: ' + checks.join('; ') + '\nNonfatal failures: ' + failures.join('; ') + '\nFailure: ' + error.message)
  }
}
